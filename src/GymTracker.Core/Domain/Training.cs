namespace GymTracker.Core.Domain;

public class Exercise
{
    public int Id { get; set; }
    public string Name { get; set; } = "";
    public Muscle PrimaryMuscle { get; set; }
    public List<Muscle> SecondaryMuscles { get; set; } = [];
    public Equipment Equipment { get; set; }

    /// <summary>Null for the shared seed library; set for a user's custom exercise.</summary>
    public string? OwnerUserId { get; set; }

    public bool IsArchived { get; set; }
}

public class WorkoutTemplate
{
    public int Id { get; set; }
    public string UserId { get; set; } = "";
    public string Name { get; set; } = "";
    public int SortOrder { get; set; }
    public bool IsArchived { get; set; }
    public List<TemplateExercise> Exercises { get; set; } = [];
}

public class TemplateExercise
{
    public const int DefaultRestSeconds = 120;

    public int Id { get; set; }
    public int TemplateId { get; set; }
    public WorkoutTemplate Template { get; set; } = null!;
    public int ExerciseId { get; set; }
    public Exercise Exercise { get; set; } = null!;
    public int SortOrder { get; set; }
    public int WorkingSets { get; set; } = 3;
    public int RepMin { get; set; } = 8;
    public int RepMax { get; set; } = 12;

    /// <summary>Null falls back to the profile's default increment.</summary>
    public decimal? WeightIncrementKg { get; set; }

    public int RestSeconds { get; set; } = DefaultRestSeconds;
}

public class WorkoutSession
{
    public int Id { get; set; }
    public string UserId { get; set; } = "";

    /// <summary>Null for a freestyle session.</summary>
    public int? TemplateId { get; set; }
    public WorkoutTemplate? Template { get; set; }

    public DateTimeOffset StartedAt { get; set; }
    public DateTimeOffset? EndedAt { get; set; }
    public string? Notes { get; set; }
    public List<SessionExercise> Exercises { get; set; } = [];

    public bool IsActive => EndedAt is null;
}

/// <summary>
/// An exercise within a session. Rep range, set count, increment and rest are copied
/// from the template at session start so later template edits don't rewrite history.
/// </summary>
public class SessionExercise
{
    public int Id { get; set; }
    public int SessionId { get; set; }
    public WorkoutSession Session { get; set; } = null!;
    public int ExerciseId { get; set; }
    public Exercise Exercise { get; set; } = null!;
    public int SortOrder { get; set; }
    public int RepMin { get; set; }
    public int RepMax { get; set; }
    public int WorkingSets { get; set; }
    public decimal WeightIncrementKg { get; set; }
    public int RestSeconds { get; set; } = TemplateExercise.DefaultRestSeconds;
    public List<SetEntry> Sets { get; set; } = [];
}

public class SetEntry
{
    public int Id { get; set; }
    public int SessionExerciseId { get; set; }
    public SessionExercise SessionExercise { get; set; } = null!;
    public int SetNumber { get; set; }
    public decimal WeightKg { get; set; }
    public int Reps { get; set; }

    /// <summary>5 to 10 in 0.5 steps, or null.</summary>
    public decimal? Rpe { get; set; }

    public bool IsWarmup { get; set; }
    public DateTimeOffset CompletedAt { get; set; }

    /// <summary>Generated by the client so a retried request doesn't create a duplicate.</summary>
    public Guid ClientId { get; set; }
}
